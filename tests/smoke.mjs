import assert from 'node:assert/strict';
import {readFileSync,existsSync,readdirSync} from 'node:fs';
import {join} from 'node:path';
import {runInNewContext} from 'node:vm';
import {execFileSync} from 'node:child_process';
const root=process.cwd();
const html=readFileSync(join(root,'index.html'),'utf8');
const scripts=[...html.matchAll(/<script\s+src="(assets\/js\/[^"?]+)(?:\?[^"]*)?"/g)].map(m=>m[1]);
const styles=[...html.matchAll(/<link\s+rel="stylesheet"\s+href="(assets\/css\/[^"?]+)(?:\?[^"]*)?"/g)].map(m=>m[1]);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
const unique=new Set(ids);
assert.equal(unique.size,ids.length,'HTML IDs must be unique');
assert.match(html,/VERSION 5\./,'Expected PassBit 5 release');
for(const file of [...scripts,...styles])assert.ok(existsSync(join(root,file)),'Missing asset '+file);
assert.equal(new Set(scripts).size,scripts.length,'Duplicate script load');
assert.equal(new Set(styles).size,styles.length,'Duplicate stylesheet');
for(const file of scripts)execFileSync(process.execPath,['--check',join(root,file)],{stdio:'pipe'});
const nav=readFileSync(join(root,'assets/js/navigation.js'),'utf8');
const bot=readFileSync(join(root,'assets/js/my-assistant.js'),'utf8');
assert.match(html,/id="my-toggle"/,'My launch button');
assert.match(html,/id="my-panel"/,'My assistant panel');
assert.match(html,/id="my-form"/,'My assistant input');
assert.match(bot,/passbitMy=/,'My assistant API');
const groupMatch=nav.match(/const taxonomy=([\s\S]*?);\nconst root=/);
assert.ok(groupMatch,'Category taxonomy must exist');
const groupIds=[...groupMatch[1].matchAll(/'([a-z][a-z0-9]*)'/g)].map(x=>x[1]);
const allTools=[...html.matchAll(/class="dashbtn" data-go="([^"]+)"/g)].map(x=>x[1]);
for(const id of allTools.filter(x=>x!=='field'))assert.ok(groupIds.includes(id),'Tool missing from categories: '+id);
for(const id of groupIds)assert.equal(groupIds.filter(x=>x===id).length,1,'Duplicate category tool '+id);

const expected=['hydcyl','hydpump','hydpipe','hydacc','pneucyl','servicevib','elec3','mechbearing','mechgear','mechbolt','belt','metrotemp','metrounc','grindwheel','hydraulics','cylinders','fittings'];
for(const id of expected){
 assert.match(html,new RegExp('id="'+id+'"'),'Missing section '+id);
 assert.match(html,new RegExp('data-go="'+id+'"'),'Missing dashboard entry '+id);
 assert.ok(nav.includes("'"+id+"'"),'Missing navigation registration '+id);
}
const context={window:{passbitToolTier:()=> 'free'},document:{getElementById:()=>null},console};
runInNewContext(readFileSync(join(root,'assets/js/engineering-suite.js'),'utf8'),context);
const c=context.window.passbit5Calculators;
assert.equal(Object.keys(c).length,14);
const near=(actual,expected,tol,label)=>assert.ok(Math.abs(actual-expected)<=tol,label+': got '+actual+' expected '+expected);
const output=(id,v)=>Object.fromEntries(c[id].compute(v).results.map(([label,value])=>[label,value]));
let r=output('hydcyl',{d:63,rod:36,p:160,q:30,stroke:500,eff:90});
near(r['Utgående kraft'],Math.PI*63**2/4*16*.9,.01,'Cylinder force');
near(r['Ingående kraft'],Math.PI*(63**2-36**2)/4*16*.9,.01,'Cylinder retract force');
r=output('hydpump',{disp:25,rpm:1450,p:180,vol:92,mech:88});
near(r['Teoretiskt flöde'],36.25,1e-9,'Pump flow');
near(r['Levererat flöde'],33.35,1e-9,'Pump delivered flow');
r=output('hydpipe',{od:16,wall:2,q:30,p:160});
near(r['Innerdiameter'],12,1e-9,'Pipe bore');
near(r['Hydraulisk effekt'],8,1e-9,'Hydraulic power');
r=output('hydacc',{p0:90,p1:110,p2:180,v0:5,n:1.4});
assert.ok(r['Uttagbar oljevolym']>0,'Accumulator must deliver positive volume');
r=output('elec3',{u:400,i:12,pf:.85,eff:90,rpm:1450});
near(r['Skenbar effekt'],Math.sqrt(3)*400*12/1000,1e-9,'Three phase apparent power');
r=output('mechbearing',{c:35,p:8,rpm:1500,kind:3});
near(r['L10 livslängd'],(35/8)**3,1e-9,'Bearing L10');
r=output('mechgear',{z1:20,z2:60,rpm:1500,torque:40,eff:95});
near(r['Utgående varvtal'],500,1e-9,'Gear ratio');
r=output('metrotemp',{length:1000,alpha:12,t0:-10,t1:30});
near(r['Längdändring'],.48,1e-9,'Negative temperature support');
r=output('metrounc',{u1:2,u2:3,u3:1,k:2});
near(r['Utvidgad osäkerhet U'],2*Math.sqrt(14),1e-9,'Uncertainty RSS');
r=output('grindwheel',{d:400,rpm:1800,limit:50});
near(r['Aktuell periferihastighet'],Math.PI*400*1800/60000,1e-9,'Wheel peripheral speed');
r=output('servicevib',{rpm:1800,teeth:24,bearing:60});
near(r['Kuggingreppsfrekvens'],720,1e-9,'Gear mesh frequency');
r=output('pneucyl',{d:40,rod:16,p:6,stroke:200,cycles:10});
assert.ok(r['Fri luft, approx.']>0,'Air demand');
r=output('belt',{d1:100,d2:250,rpm:1450,c:500});
near(r['Drivet varvtal'],580,1e-9,'Belt speed');
r=output('mechbolt',{torque:80,d:12,k:.2});
near(r['Beräknad förspänning'],80/(.2*.012)/1000,1e-9,'Bolt preload');
assert.throws(()=>c.hydcyl.compute({d:40,rod:50,p:160,q:30,stroke:100,eff:90}));
assert.throws(()=>c.hydacc.compute({p0:120,p1:110,p2:180,v0:5,n:1.4}));
assert.throws(()=>c.grindwheel.compute({d:0,rpm:1800,limit:50}));
console.log('PassBit QA passed:',scripts.length,'JavaScript assets,',styles.length,'stylesheets,',ids.length,'unique HTML IDs,',expected.length,'navigation tools, 14 numerical models and edge cases.');
